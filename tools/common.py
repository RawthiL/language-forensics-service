"""Backend-agnostic helpers for building the Triton model repository.

Used by every `backends/<family>/export.py` and `triton_repo.py`. Keeps torch
out of the picture: `build_config_pbtxt` / `inspect_onnx` only need `onnx`.

The metadata dict written into `config.pbtxt` is the contract between a
backend's exporter and the same backend's Rust crate. Fields every backend
writes (parsed by `backend-api` `CommonMeta`, checked by `verify_repo.py`):

family            : str, selects the gateway backend (e.g. "horizon-guard")
task              : "prompt-injection"
labels            : list[str], indexed by logit position
positive          : list[int], logit positions summed into the injection score
inputs            : list[str], ONNX input names (input_ids, attention_mask[, token_type_ids])
outputs           : list[str], the ONNX logits output name
tokenizer         : str, tokenizer file name inside the model directory
tokenizer_sha256  : str, its sha256 (the gateway refuses a mismatching file)
max_tokens        : int, longest sequence the model accepts
window, stride    : int, recommended window policy (tokens, specials included)
pad_id            : int, padding token id
onnx_sha256       : str, sha256 of 1/model.onnx (model fingerprint)
source            : {"repo", "revision", "file"} or {"path"} — where the weights came from
license           : str, SPDX id or name of the WEIGHTS license

The tokenizer file lives next to config.pbtxt. Triton ignores it; the gateway
reads it from its own read-only mount of the same repository.
"""

from __future__ import annotations

import hashlib
import json
import shutil
from pathlib import Path
from typing import Any

TASK = "prompt-injection"

_ONNX_DTYPE_TO_TRITON = {
    1: "TYPE_FP32",   # float
    6: "TYPE_INT32",
    7: "TYPE_INT64",
    10: "TYPE_FP16",  # float16
    11: "TYPE_FP64",
}


def _escape_proto_string(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build_config_pbtxt(
    *,
    model_name: str,
    metadata: dict[str, Any],
    input_specs: list[dict[str, Any]],
    output_specs: list[dict[str, Any]],
    max_batch_size: int = 16,
    queue_delay_us: int = 2000,
    preferred_batch_sizes: tuple[int, ...] = (4, 8, 16),
    instance_group_count: int | None = None,
) -> str:
    """Render a Triton `config.pbtxt` for an onnxruntime text classifier.

    With `max_batch_size > 0` the io dims exclude the batch dim (e.g.
    `[-1]` for a token sequence). With `max_batch_size=0` they carry full
    graph dims and concurrency comes from `instance_group_count`.
    """
    meta_json = json.dumps(metadata, separators=(",", ":"), ensure_ascii=True)

    lines = [
        f"# Auto-generated by backends/<family> tooling for '{model_name}'. Do not edit by hand.",
        'backend: "onnxruntime"',
        f"name: {_escape_proto_string(model_name)}",
        f"max_batch_size: {max_batch_size}",
    ]
    if max_batch_size >= 2:
        preferred = ", ".join(str(b) for b in preferred_batch_sizes if b <= max_batch_size)
        lines += [
            "dynamic_batching {",
            f"  preferred_batch_size: [{preferred}]",
            f"  max_queue_delay_microseconds: {queue_delay_us}",
            "}",
        ]
    if instance_group_count:
        lines += ["instance_group [", f"  {{ count: {instance_group_count} }}", "]"]
    head = "\n".join(lines + ["input ["])
    body = _render_entries(input_specs) + "]\noutput [\n" + _render_entries(output_specs) + "]"
    tail = (
        "\nparameters {\n"
        '  key: "metadata"\n'
        f"  value {{ string_value: {_escape_proto_string(meta_json)} }}\n"
        "}\n"
    )
    return head + "\n" + body + tail


def _render_entries(specs: list[dict[str, Any]]) -> str:
    out = []
    for s in specs:
        dims = ", ".join(str(d) for d in s["dims"])
        out.append(
            "  {\n"
            f"    name: {_escape_proto_string(s['name'])}\n"
            f"    data_type: {s['data_type']}\n"
            f"    dims: [ {dims} ]\n"
            "  }"
        )
    return ",\n".join(out) + "\n"


def inspect_onnx(path: Path) -> dict[str, Any]:
    """Return input/output tensor names, element types, (symbolic) dims, and
    the external-data files the graph references (relative to its folder)."""
    import onnx

    model = onnx.load(str(path), load_external_data=False)
    graph = model.graph
    init_names = {i.name for i in graph.initializer}

    def dims(value_info):
        res = []
        for d in value_info.type.tensor_type.shape.dim:
            if d.HasField("dim_value"):
                res.append(int(d.dim_value))
            else:
                res.append(d.dim_param or "?")
        return res

    def entry(v):
        return {"name": v.name, "elem": v.type.tensor_type.elem_type, "dims": dims(v)}

    external = sorted({
        kv.value
        for init in graph.initializer
        if init.data_location == onnx.TensorProto.EXTERNAL
        for kv in init.external_data
        if kv.key == "location"
    })
    return {
        "inputs": [entry(i) for i in graph.input if i.name not in init_names],
        "outputs": [entry(o) for o in graph.output],
        "external_data": external,
    }


def triton_dtype(onnx_elem: int) -> str:
    """Map an ONNX element type id to Triton's TYPE_* enum name."""
    try:
        return _ONNX_DTYPE_TO_TRITON[onnx_elem]
    except KeyError:
        raise ValueError(f"unsupported ONNX element type {onnx_elem}") from None


def sha256_file(path: Path, chunk: int = 1 << 20) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while block := f.read(chunk):
            h.update(block)
    return h.hexdigest()


def write_repo(
    repo_dir: Path,
    model_name: str,
    onnx_path: Path,
    config_text: str,
    *,
    tokenizer_path: Path,
    tokenizer_name: str = "tokenizer.json",
) -> Path:
    """Write `<repo>/<name>/{config.pbtxt, tokenizer.json, 1/model.onnx}`.

    Other files already in `<repo>/<name>/` (an upstream checkout exported in
    place: LICENSE, safetensors, ...) are left alone; Triton ignores them.
    External-data files referenced by the graph (e.g. `model.onnx_data`) are
    copied next to `model.onnx` under the same relative name. Stale files from
    a previous export of the same name are removed first.
    """
    model_dir = repo_dir / model_name
    version_dir = model_dir / "1"
    if version_dir.exists():
        shutil.rmtree(version_dir)
    version_dir.mkdir(parents=True)
    # copyfile, not copy2: Hugging Face cache blobs are read-only, and their
    # mode must not make the next export of the same name fail.
    shutil.copyfile(onnx_path, version_dir / "model.onnx")
    for rel in inspect_onnx(onnx_path)["external_data"]:
        dest = version_dir / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(onnx_path.parent / rel, dest)
    tok_dest = model_dir / tokenizer_name
    # In-place exports (the checkpoint directory IS the model directory)
    # already have the tokenizer where it belongs.
    if not (tok_dest.exists() and tok_dest.resolve() == tokenizer_path.resolve()):
        tok_dest.unlink(missing_ok=True)
        shutil.copyfile(tokenizer_path, tok_dest)
    (model_dir / "config.pbtxt").write_text(config_text)
    return model_dir


ROOT = Path(__file__).resolve().parents[1]
BACKENDS_DIR = ROOT / "backends"


def load_backend_modules(module: str = "triton_repo") -> dict[str, Any]:
    """Import `backends/<family>/<module>.py` for every backend folder.

    Returns {family: module}. Each module must define `FAMILY`.
    """
    import importlib.util

    found: dict[str, Any] = {}
    for path in sorted(BACKENDS_DIR.glob(f"*/{module}.py")):
        spec = importlib.util.spec_from_file_location(f"backend_{path.parent.name}_{module}", path)
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)
        found[mod.FAMILY] = mod
    return found


def has_dynamic_batch(dims: list) -> bool:
    """True if an ONNX tensor's first dim is symbolic (required by Triton
    whenever `max_batch_size > 0`)."""
    return bool(dims) and not isinstance(dims[0], int)


def check_onnx_matches_batching(onnx_path: Path, max_batch_size: int) -> None:
    """Enforce Triton's rule: a batching model (max_batch_size > 0) must have a
    dynamic first dim on every input; a non-batching one may be static."""
    if max_batch_size <= 0:
        return
    for i in inspect_onnx(onnx_path)["inputs"]:
        if not has_dynamic_batch(i["dims"]):
            raise AssertionError(
                f"max_batch_size={max_batch_size} but ONNX input '{i['name']}' has a static "
                f"batch dim {i['dims']}; Triton will refuse to load it. Re-export with a "
                "dynamic batch or set max_batch_size: 0 with explicit full dims."
            )


def classifier_io_specs(onnx_info: dict[str, Any], num_labels: int, max_batch_size: int):
    """Triton input/output specs for a `[batch, seq] -> [batch, labels]`
    classifier, validated against the ONNX graph."""
    b = [] if max_batch_size > 0 else [-1]
    inputs = []
    for i in onnx_info["inputs"]:
        if len(i["dims"]) != 2:
            raise SystemExit(f"ONNX input {i['name']} has dims {i['dims']}, expected [batch, seq]")
        inputs.append({"name": i["name"], "data_type": triton_dtype(i["elem"]), "dims": [*b, -1]})
    if len(onnx_info["outputs"]) != 1:
        raise SystemExit(f"expected one logits output, got {[o['name'] for o in onnx_info['outputs']]}")
    out = onnx_info["outputs"][0]
    last = out["dims"][-1]
    if isinstance(last, int) and last != num_labels:
        raise SystemExit(f"output {out['name']} has {last} logits but config lists {num_labels} labels")
    outputs = [{"name": out["name"], "data_type": triton_dtype(out["elem"]), "dims": [*b, num_labels]}]
    return inputs, outputs


# --- shared fixture model ---------------------------------------------------
# A tiny word-level tokenizer plus a graph that fires on one word. Backends
# use it in `make_fixture` with their own labels and window policy, so the
# contract tests exercise windowing, spans and aggregation for real without
# weights.

FIXTURE_SPECIALS = ["[PAD]", "[CLS]", "[SEP]", "[UNK]"]
FIXTURE_TRIGGER = "ignore"
FIXTURE_TRIGGER_ID = len(FIXTURE_SPECIALS)


def fixture_tokenizer(path: Path) -> None:
    """Word-level tokenizer with the same normalizer *kind* real models use
    (tag-character decoding + NFKC + invisible stripping), so the gateway's
    span mapping is exercised through a non-trivial normalizer."""
    from tokenizers import Regex, Tokenizer, normalizers, pre_tokenizers, processors
    from tokenizers.models import WordLevel

    vocab = {t: i for i, t in enumerate([*FIXTURE_SPECIALS, FIXTURE_TRIGGER])}
    tok = Tokenizer(WordLevel(vocab, unk_token="[UNK]"))
    tags = [normalizers.Replace(chr(0xE0000 + c), chr(c)) for c in range(0x20, 0x7F)]
    tok.normalizer = normalizers.Sequence([
        *tags,
        normalizers.NFKC(),
        normalizers.Replace(Regex("[\u200b-\u200f\u2060-\u2064\ufeff]"), ""),
        normalizers.Lowercase(),
    ])
    tok.pre_tokenizer = pre_tokenizers.Whitespace()
    tok.post_processor = processors.TemplateProcessing(
        single="[CLS] $A [SEP]", special_tokens=[("[CLS]", 1), ("[SEP]", 2)],
    )
    tok.save(str(path))


def fixture_onnx(path: Path, num_labels: int = 2, positive: int = 1) -> None:
    """`logits[b, positive] = z`, every other logit `-z`, with
    `z = 10 * max_t(ids[b,t] == TRIGGER & mask) - 5`: a window containing the
    trigger scores ~0.99995 (binary head), any other ~0.00005."""
    import numpy as np
    import onnx
    from onnx import TensorProto, helper, numpy_helper

    cols = ["_inj" if i == positive else "_safe" for i in range(num_labels)]
    nodes = [
        helper.make_node("Equal", ["input_ids", "_trigger"], ["_hit"]),
        helper.make_node("Cast", ["_hit"], ["_hitf"], to=TensorProto.FLOAT),
        helper.make_node("Cast", ["attention_mask"], ["_maskf"], to=TensorProto.FLOAT),
        helper.make_node("Mul", ["_hitf", "_maskf"], ["_live"]),
        helper.make_node("ReduceMax", ["_live"], ["_any"], axes=[1], keepdims=1),
        helper.make_node("Mul", ["_any", "_ten"], ["_scaled"]),
        helper.make_node("Sub", ["_scaled", "_five"], ["_inj"]),
        helper.make_node("Neg", ["_inj"], ["_safe"]),
        helper.make_node("Concat", cols, ["logits"], axis=1),
    ]
    inits = [
        numpy_helper.from_array(np.array(FIXTURE_TRIGGER_ID, dtype=np.int64), "_trigger"),
        numpy_helper.from_array(np.array(10.0, dtype=np.float32), "_ten"),
        numpy_helper.from_array(np.array(5.0, dtype=np.float32), "_five"),
    ]
    graph = helper.make_graph(
        nodes, "trigger_fixture",
        [helper.make_tensor_value_info("input_ids", TensorProto.INT64, ["batch", "seq"]),
         helper.make_tensor_value_info("attention_mask", TensorProto.INT64, ["batch", "seq"])],
        [helper.make_tensor_value_info("logits", TensorProto.FLOAT, ["batch", num_labels])],
        inits,
    )
    model = helper.make_model(graph, opset_imports=[helper.make_opsetid("", 17)])
    model.ir_version = 9
    onnx.checker.check_model(model)
    onnx.save(model, str(path))


def write_fixture(repo: Path, workdir: Path, *, name: str, family: str, labels: list[str],
                  positive: int, window: int = 16, stride: int = 4, max_tokens: int = 64,
                  license: str = "MIT") -> str:
    """Build the trigger fixture with a family's labels and write its repo."""
    tok_path = workdir / f"{name}-tokenizer.json"
    onnx_path = workdir / f"{name}.onnx"
    fixture_tokenizer(tok_path)
    fixture_onnx(onnx_path, len(labels), positive)
    inputs, outputs = classifier_io_specs(inspect_onnx(onnx_path), len(labels), 16)
    metadata = {
        "family": family, "task": TASK,
        "labels": labels, "positive": [positive],
        "inputs": ["input_ids", "attention_mask"], "outputs": ["logits"],
        "tokenizer": "tokenizer.json", "tokenizer_sha256": sha256_file(tok_path),
        "max_tokens": max_tokens, "window": window, "stride": stride,
        "pad_id": 0, "onnx_sha256": sha256_file(onnx_path),
        "source": {"fixture": True}, "license": license,
    }
    write_repo(repo, name, onnx_path, build_config_pbtxt(
        model_name=name, metadata=metadata,
        input_specs=inputs, output_specs=outputs, max_batch_size=16,
    ), tokenizer_path=tok_path)
    return name
